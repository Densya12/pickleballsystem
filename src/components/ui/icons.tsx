/**
 * Decorative icons. Always rendered aria-hidden: every icon in this app is
 * paired with visible text, so the text carries the meaning.
 */
type IconProps = Omit<SVGProps<SVGSVGElement>, "aria-hidden" | "children">;

function Icon({ children, className, ...props }: IconProps & { children: ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2.25}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={className ?? "size-5 shrink-0"}
      {...props}
    >
      {children}
    </svg>
  );
}

